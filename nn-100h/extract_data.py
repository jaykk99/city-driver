#!/usr/bin/env python3
"""Extract the nn-100h dataset from the game's own authored data.

Reads js/cars.js (CAR_DEFS) from the repo checkout and writes
nn-100h/dataset.jsonl. Every value is parsed mechanically out of the
source file; nothing is hand-typed, nothing is invented.

Task: predict whether a car is premium-tier (price >= $20,000) from
its six performance stats. Price itself is NOT a feature: the label
is derived from it, so including it would be direct leakage.

Why cars, not taxi fares: the repo holds no real recorded ride data.
PR #3's 1,000 fares were generated by driving js/taxi.js with seeded
RNGs that invent each fare's pace, damage, weather and ratings, and
the tip label is a deterministic function of the features (see
DATASET.md). No playtest or telemetry log exists anywhere in the repo
or its git history. The 17 CAR_DEFS rows are the largest coherent,
authored, non-deterministic table in the repo, so they are the dataset.

Usage: python3 extract_data.py   (run from nn-100h/)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent
CARS_JS = REPO_ROOT / "js" / "cars.js"
OUT = HERE / "dataset.jsonl"

PREMIUM_PRICE = 20000  # $; label 1 = premium tier, 0 = standard tier

# stats:{ topSpeed:52, accel:16, handling:1.0, grip:1.0,
#         nitroTime:3.2, nitroPower:1.35 }
ENTRY_RE = re.compile(
    r"\{\s*id:'(?P<id>[a-z0-9_]+)',\s*name:'(?P<name>[^']*)',"
    r".*?price:(?P<price>\d+),"
    r".*?stats:\{\s*topSpeed:(?P<topSpeed>[\d.]+),\s*accel:(?P<accel>[\d.]+),"
    r"\s*handling:(?P<handling>[\d.]+),\s*grip:(?P<grip>[\d.]+),"
    r"\s*nitroTime:(?P<nitroTime>[\d.]+),\s*nitroPower:(?P<nitroPower>[\d.]+)\s*\}",
    re.DOTALL,
)

FEATURES = ["topSpeed", "accel", "handling", "grip", "nitroTime", "nitroPower"]


def main() -> int:
    text = CARS_JS.read_text(encoding="utf-8")
    rows = []
    for m in ENTRY_RE.finditer(text):
        price = int(m.group("price"))
        feats = {f: float(m.group(f)) for f in FEATURES}
        rows.append({
            "car_id": m.group("id"),
            "name": m.group("name"),
            "price": price,
            "features": feats,
            "label": 1 if price >= PREMIUM_PRICE else 0,
            "label_name": "premium" if price >= PREMIUM_PRICE else "standard",
            "source": "js/cars.js CAR_DEFS",
        })
    if not rows:
        print("ERROR: no CAR_DEFS rows parsed from %s" % CARS_JS, file=sys.stderr)
        return 1
    # Sanity: ids unique, prices match the file's own price list.
    ids = [r["car_id"] for r in rows]
    assert len(set(ids)) == len(ids), "duplicate car ids parsed"
    with open(OUT, "w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r) + "\n")
    n_pos = sum(r["label"] for r in rows)
    print(f"wrote {len(rows)} rows to {OUT} "
          f"({n_pos} premium / {len(rows) - n_pos} standard)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
